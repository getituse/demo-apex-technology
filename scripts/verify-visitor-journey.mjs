/* global document -- Playwright callbacks execute in Chromium */
import assert from "node:assert/strict";
import fs from "node:fs";
import http from "node:http";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

import { rawConfig as config } from "../src/site/config.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");
const outputDir = path.join(root, "build");
const screenshotsDir = path.join(outputDir, "journey-screenshots");
fs.mkdirSync(outputDir, { recursive: true });
fs.mkdirSync(screenshotsDir, { recursive: true });

const mime = {
  ".html": "text/html",
  ".js": "text/javascript",
  ".css": "text/css",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".json": "application/json",
  ".woff2": "font/woff2",
  ".pdf": "application/pdf",
};

function serveStatic(distDir) {
  return http.createServer((req, res) => {
    try {
      const pathname = decodeURIComponent(new URL(req.url, "http://localhost").pathname);
      let filepath = path.resolve(distDir, `.${pathname}`);
      if (!filepath.startsWith(distDir)) {
        res.writeHead(400).end();
        return;
      }
      if (fs.existsSync(filepath) && fs.statSync(filepath).isDirectory()) {
        filepath = path.join(filepath, "index.html");
      }
      if (!fs.existsSync(filepath)) {
        res.writeHead(404, { "Content-Type": "text/html" });
        res.end(fs.readFileSync(path.join(distDir, "404.html")));
        return;
      }
      res.writeHead(200, {
        "Content-Type": mime[path.extname(filepath)] ?? "application/octet-stream",
        "Content-Length": fs.statSync(filepath).size,
      });
      res.end(fs.readFileSync(filepath));
    } catch {
      res.writeHead(500).end();
    }
  });
}

const report = {
  startedAt: new Date().toISOString(),
  tenantId: config.id,
  ok: false,
  collections: {
    newsEventsChecked: false,
    initialHtmlRecords: 0,
    pagesTraversed: 0,
    categoriesTested: 0,
  },
  gallery: { enabled: config.pages.gallery?.enabled ?? false, tested: false },
  downloads: { verifiedCount: 0, files: [] },
  navigation: { backForwardHops: 0, allHeadingsFocused: false },
  reducedMotion: { testedRoutes: 0, ok: false },
  zeroEgress: { externalRequests: 0, ok: false },
  failures: [],
};

const server = serveStatic(dist);
await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true });

try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const externalAttempts = [];
  const interceptedRequests = [];

  context.on("request", (req) => {
    interceptedRequests.push(req.url());
    if (!req.url().startsWith(origin)) {
      externalAttempts.push(req.url());
    }
  });

  const page = await context.newPage();

  // 1. Collections: News & Events pagination and filtering
  console.log(`[1/5] Testing collections on ${config.pages.newsEvents?.path}...`);
  const newsPath = config.pages.newsEvents.path;
  const rawHtml = fs.readFileSync(
    path.join(dist, newsPath.replace(/^\//, ""), "index.html"),
    "utf8",
  );
  // Count articles/cards in raw initial HTML
  const rawArticleMatches = rawHtml.match(/<article[\s>]/g) || [];
  report.collections.initialHtmlRecords = rawArticleMatches.length;
  assert(
    report.collections.initialHtmlRecords > 0,
    "Initial HTML must contain complete collection records",
  );

  await page.goto(`${origin}${newsPath}`, { waitUntil: "networkidle" });
  await page.locator("main h1").waitFor();

  // Check category filter if select exists
  const categorySelect = page.locator('select[id*="-category"]').first();
  if ((await categorySelect.count()) > 0) {
    const options = await categorySelect.locator("option").allTextContents();
    const selectable = options.filter((opt) => opt && !opt.includes("All"));
    for (const cat of selectable.slice(0, 3)) {
      await categorySelect.selectOption({ label: cat });
      await page.waitForTimeout(100);
      report.collections.categoriesTested++;
    }
    // Reset to all
    await categorySelect.selectOption({ index: 0 });
    await page.waitForTimeout(100);
  }

  // Check pagination
  const nextButton = page.getByRole("button", { name: /Next page/i }).first();
  let pagesTraversed = 1;
  const initialUrl = page.url();
  while ((await nextButton.count()) > 0 && (await nextButton.isEnabled()) && pagesTraversed < 5) {
    const startRequestsCount = interceptedRequests.length;
    await nextButton.click();
    await page.waitForTimeout(100);
    // Assert zero new network requests were generated by pagination
    const newNetworkRequests = interceptedRequests
      .slice(startRequestsCount)
      .filter((url) => !url.match(/\.(png|jpg|svg|woff2)$/));
    assert.equal(
      newNetworkRequests.length,
      0,
      "Pagination must be local; no fetch/document requests",
    );
    assert.equal(page.url(), initialUrl, "Local pagination must not modify canonical URL");
    pagesTraversed++;
  }
  report.collections.pagesTraversed = pagesTraversed;
  report.collections.newsEventsChecked = true;
  await page.screenshot({ path: path.join(screenshotsDir, "collections-paginated.png") });

  // 2. Gallery Lightbox
  console.log(`[2/5] Testing gallery lightbox...`);
  if (config.pages.gallery?.enabled) {
    await page.goto(`${origin}${config.pages.gallery.path}`, { waitUntil: "networkidle" });
    await page.locator("main h1").waitFor();
    const firstThumb = page.locator('main [data-section-type="imageGallery"] button').first();
    if ((await firstThumb.count()) > 0) {
      await firstThumb.focus();
      await page.keyboard.press("Enter");
      const dialog = page.getByRole("dialog");
      await dialog.waitFor({ state: "visible", timeout: 5000 });
      // Verify arrow key navigation
      const desc1 = await dialog.locator("p").first().textContent();
      await page.keyboard.press("ArrowRight");
      await page.waitForTimeout(150);
      const desc2 = await dialog.locator("p").first().textContent();
      assert.notEqual(desc1, desc2, "ArrowRight must change active gallery image");
      await page.keyboard.press("ArrowLeft");
      await page.waitForTimeout(150);
      // Close with Escape and assert focus restoration
      await page.keyboard.press("Escape");
      await dialog.waitFor({ state: "hidden", timeout: 5000 });
      assert(
        await firstThumb.evaluate((el) => el === document.activeElement),
        "Escape must restore focus to thumbnail",
      );
      report.gallery.tested = true;
      await page.screenshot({ path: path.join(screenshotsDir, "gallery-verified.png") });
    }
  } else {
    // Gallery is disabled (Northstar Academy)
    const galleryRes = await page.goto(`${origin}/gallery`, { waitUntil: "networkidle" });
    assert.equal(galleryRes.status(), 404, "Disabled gallery must serve genuine 404");
    report.gallery.tested = true;
  }

  // 3. Downloads: verify every linked PDF and asset
  console.log(`[3/5] Verifying all linked downloads...`);
  if (config.pages.downloads?.enabled) {
    await page.goto(`${origin}${config.pages.downloads.path}`, { waitUntil: "networkidle" });
    const downloadLinks = await page.locator('a[href$=".pdf"]').all();
    for (const link of downloadLinks) {
      const href = await link.getAttribute("href");
      if (href) {
        const fullUrl = new URL(href, origin).href;
        const res = await page.request.get(fullUrl);
        assert.equal(res.status(), 200, `Download link ${href} must return HTTP 200`);
        const buffer = await res.body();
        assert(buffer.length > 0, `Download file ${href} must have non-zero length`);
        assert.equal(
          res.headers()["content-type"],
          "application/pdf",
          `Download ${href} must be application/pdf`,
        );
        report.downloads.verifiedCount++;
        report.downloads.files.push({ href, bytes: buffer.length });
      }
    }
  }

  // 4. Multi-hop visitor navigation with Back/Forward heading focus check
  console.log(`[4/5] Testing visitor navigation and Back/Forward focus management...`);
  await page.goto(`${origin}/`, { waitUntil: "networkidle" });
  await page.waitForFunction(() => document.querySelector("main h1"));

  // Click real links in header navigation
  const primaryNav = page.locator('header nav[aria-label="Primary"]');
  const aboutLink = primaryNav
    .getByRole("link", { name: config.pages.about.navLabel, exact: true })
    .first();
  await aboutLink.click();
  await page.waitForFunction(() => document.activeElement === document.querySelector("main h1"));

  const contactLink = primaryNav
    .getByRole("link", { name: config.pages.contact.navLabel, exact: true })
    .first();
  await contactLink.click();
  await page.waitForFunction(() => document.activeElement === document.querySelector("main h1"));

  // Perform 6 Back and Forward navigations, checking heading focus on each transition
  let hops = 0;
  for (let i = 0; i < 2; i++) {
    await page.goBack();
    await page.waitForFunction(() => document.activeElement === document.querySelector("main h1"));
    hops++;
  }
  for (let i = 0; i < 2; i++) {
    await page.goForward();
    await page.waitForFunction(() => document.activeElement === document.querySelector("main h1"));
    hops++;
  }
  for (let i = 0; i < 2; i++) {
    await page.goBack();
    await page.waitForFunction(() => document.activeElement === document.querySelector("main h1"));
    hops++;
  }
  report.navigation.backForwardHops = hops;
  report.navigation.allHeadingsFocused = true;

  // 5. Reduced Motion
  console.log(`[5/5] Testing reduced-motion on home, detail, and form...`);
  await page.emulateMedia({ reducedMotion: "reduce" });
  for (const testPath of [
    config.pages.home.path,
    config.pages.about.path,
    config.pages.contact.path,
  ]) {
    await page.goto(`${origin}${testPath}`, { waitUntil: "networkidle" });
    await page.locator("main h1").waitFor();
    const visible = await page.locator("main h1").isVisible();
    assert(visible, `Heading on ${testPath} must remain visible under reduced motion`);
    report.reducedMotion.testedRoutes++;
  }
  report.reducedMotion.ok = true;

  // Final Zero-Egress Assertion
  report.zeroEgress.externalRequests = externalAttempts.length;
  report.zeroEgress.ok = externalAttempts.length === 0;
  assert.equal(
    externalAttempts.length,
    0,
    `Zero third-party requests permitted; saw: ${externalAttempts.join(", ")}`,
  );

  report.ok = true;
  console.log(`PASS ${config.brand.name}: visitor journey verified`);
} catch (error) {
  report.failures.push(error instanceof Error ? error.stack : String(error));
  console.error(`FAIL: ${error.message}`);
} finally {
  await browser.close();
  await new Promise((resolve) => server.close(resolve));
  fs.writeFileSync(
    path.join(outputDir, "visitor-journey-audit.json"),
    JSON.stringify(report, null, 2),
    "utf8",
  );
  process.exitCode = report.ok ? 0 : 1;
}
